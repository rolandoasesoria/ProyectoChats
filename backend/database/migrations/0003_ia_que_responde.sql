-- IA que responde a los clientes por WhatsApp (modo supervisado o automático).

-- Mensajes enviados por la IA (se muestran marcados como tales).
ALTER TABLE messages ADD COLUMN IF NOT EXISTS by_ai SMALLINT NOT NULL DEFAULT 0;

-- Conversaciones en las que se ha pausado la IA (no responde en ellas aunque esté activada).
CREATE TABLE IF NOT EXISTS ai_paused_conversations (
    conversation_id  BIGINT PRIMARY KEY REFERENCES conversations(id) ON DELETE CASCADE,
    paused_by        BIGINT REFERENCES users(id) ON DELETE SET NULL,
    paused_at        TIMESTAMP NOT NULL DEFAULT localtimestamp(0)
);

-- Qué ha hecho la IA con cada mensaje del cliente: propuesta pendiente de aprobar, enviada, descartada, pasada a una
-- persona (handoff) o fallida. Un mensaje del cliente se trata una sola vez.
CREATE TABLE IF NOT EXISTS ai_replies (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id  BIGINT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
    message_id       BIGINT NOT NULL REFERENCES messages(id) ON DELETE CASCADE,
    status           TEXT NOT NULL CHECK (status IN ('pending', 'sent', 'discarded', 'handoff', 'failed')),
    text             TEXT NOT NULL DEFAULT '',
    reason           TEXT NOT NULL DEFAULT '',
    created_at       TIMESTAMP NOT NULL DEFAULT localtimestamp(0),
    decided_by       BIGINT REFERENCES users(id) ON DELETE SET NULL,
    decided_at       TIMESTAMP,
    UNIQUE (conversation_id, message_id)
);
CREATE INDEX IF NOT EXISTS idx_ai_replies_status ON ai_replies (conversation_id, status);
