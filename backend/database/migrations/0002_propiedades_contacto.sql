-- Propiedades de contacto: campos que define un administrador (DNI, nacionalidad, fecha de inicio…) y su valor en
-- cada cliente. Los «datos clave» que extrae la IA (client_facts) siguen aparte: estos son campos fijos de la ficha.

CREATE TABLE IF NOT EXISTS contact_properties (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label       TEXT NOT NULL,
    kind        TEXT NOT NULL CHECK (kind IN ('text', 'number', 'date', 'select')),
    options     TEXT NOT NULL DEFAULT '[]',     -- JSON: opciones de las de tipo «select»
    position    INTEGER NOT NULL DEFAULT 0,
    created_at  TIMESTAMP NOT NULL DEFAULT localtimestamp(0)
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_contact_properties_label ON contact_properties (lower(label));

CREATE TABLE IF NOT EXISTS client_property_values (
    client_id    BIGINT NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
    property_id  BIGINT NOT NULL REFERENCES contact_properties(id) ON DELETE CASCADE,
    value        TEXT NOT NULL,
    updated_by   BIGINT REFERENCES users(id) ON DELETE SET NULL,
    updated_at   TIMESTAMP NOT NULL DEFAULT localtimestamp(0),
    PRIMARY KEY (client_id, property_id)
);
CREATE INDEX IF NOT EXISTS idx_client_property_values_property ON client_property_values (property_id);
